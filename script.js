function pick(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
}

function buildChildrenText(compType) {
    let kids = [];
    switch (compType) {
        case "one_girl":       kids = ["дочь"]; break;
        case "one_boy":        kids = ["сын"]; break;
        case "two_girls":      kids = ["старшая дочь", "младшая дочь"]; break;
        case "two_boys":       kids = ["старший сын", "младший сын"]; break;
        case "boy_girl":
            kids = Math.random() < 0.5
                ? ["старший сын", "младшая дочь"]
                : ["старшая дочь", "младший сын"];
            break;
        case "three_mixed_1":  kids = ["старшая дочь", "средняя дочь", "младший сын"]; break;
        case "three_mixed_2":  kids = ["старший сын", "средний сын", "младшая дочь"]; break;
        case "three_girls":    kids = ["старшая дочь", "средняя дочь", "младшая дочь"]; break;
        case "three_boys":     kids = ["старший сын", "средний сын", "младший сын"]; break;
    }
    const usedTraits = new Set();
    return kids.map(k => {
        let trait;
        do { trait = pick(childTraits); } while (usedTraits.has(trait));
        usedTraits.add(trait);
        const isFemale = k.includes("дочь");
        return `— ${k.charAt(0).toUpperCase() + k.slice(1)}: школьник${isFemale ? "ица" : ""}, ${trait}`;
    }).join("\n");
}

function getLocationPhrase(locationValue) {
    if (cities.includes(locationValue)) return `в городе ${locationValue}`;
    if (suburbs.includes(locationValue)) return `в пригороде: ${locationValue}`;
    if (villages.includes(locationValue)) return `в ${locationValue}`;
    if (villagesSmall.includes(locationValue)) return `в ${locationValue}`;
    return `в ${locationValue}`;
}


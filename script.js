function copyToClipboard() {
    const text = document.getElementById('promptOutput').textContent;
    if (navigator.clipboard && window.isSecureContext) {
        navigator.clipboard.writeText(text).then(() => showCopyStatus('✅ Промпт скопирован в буфер обмена!'))
            .catch(() => fallbackCopy(text));
    } else {
        fallbackCopy(text);
    }
}

function fallbackCopy(text) {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.position = 'fixed';
    ta.style.left = '-999999px';
    document.body.appendChild(ta);
    ta.focus(); ta.select();
    try {
        const ok = document.execCommand('copy');
        showCopyStatus(ok ? '✅ Промпт скопирован!' : '❌ Не удалось скопировать.');
    } catch {
        showCopyStatus('❌ Не удалось скопировать. Скопируйте вручную.');
    }
    document.body.removeChild(ta);
}

function showCopyStatus(msg) {
    const el = document.getElementById('copyStatus');
    el.textContent = msg;
    el.style.opacity = '1';
    setTimeout(() => { el.style.opacity = '0'; }, 3000);
}

function openGemini() {
    const text = document.getElementById('promptOutput').textContent;
    const url = 'https://gemini.google.com/u/1/app?pageId=none';
    if (navigator.clipboard && window.isSecureContext) {
        navigator.clipboard.writeText(text).then(() => {
            showCopyStatus('✅ Промпт скопирован! Открываю Gemini...');
            setTimeout(() => window.open(url, '_blank'), 500);
        }).catch(() => { fallbackCopy(text); window.open(url, '_blank'); });
    } else { fallbackCopy(text); window.open(url, '_blank'); }
}


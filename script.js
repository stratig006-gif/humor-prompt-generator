function fillSelect(id, items, labelFn) {
    const sel = document.getElementById(id);
    items.forEach(item => {
        const opt = document.createElement('option');
        opt.value = typeof item === 'object' ? item.type : item;
        opt.textContent = labelFn ? labelFn(item) : item;
        sel.appendChild(opt);
    });
}

